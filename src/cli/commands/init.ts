import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import type { Command } from 'commander';
import { ConfigError } from '../../utils/errors.js';
import { pathExists } from '../../utils/fs.js';
import { globalOptions } from '../context.js';
import { color, print, printJson } from '../output.js';
import { CONFIG_TEMPLATE } from '../../config/defaults.js';

const STORAGE_GITIGNORE = `# Generated by scriptdrift init.
# Baselines (baselines/) are meant to be committed after review.
# Scan output may contain URLs and metadata from third parties; keep it out of Git by default.
reports/
cache/
state/
evidence/
`;

export function registerInit(program: Command): void {
  program
    .command('init')
    .description('Create a scriptdrift.yml configuration and the .scriptdrift/ directory')
    .option('--url <url>', 'website URL to pre-fill in the configuration')
    .option('--name <name>', 'site name to pre-fill', 'my-site')
    .option('--force', 'overwrite an existing scriptdrift.yml')
    .action(async (opts: { url?: string; name: string; force?: boolean }, command: Command) => {
      const g = globalOptions(command);
      const cwd = process.cwd();
      const configPath = resolve(cwd, g.config ?? 'scriptdrift.yml');
      if ((await pathExists(configPath)) && !opts.force) {
        throw new ConfigError(`${configPath} already exists`, 'Use --force to overwrite it.');
      }
      if (!/^[a-z0-9][a-z0-9._-]{0,63}$/i.test(opts.name)) throw new ConfigError(`Invalid site name "${opts.name}"`);
      if (opts.url) {
        try {
          const u = new URL(opts.url);
          if (!['http:', 'https:'].includes(u.protocol)) throw new Error('scheme');
        } catch {
          throw new ConfigError(`Invalid --url "${opts.url}"`, 'Use a full URL such as https://example.com');
        }
      }
      const text = CONFIG_TEMPLATE.replace('__SITE_NAME__', opts.name).replace('__SITE_URL__', opts.url ?? 'https://example.com');
      await writeFile(configPath, text, 'utf8');

      const storage = join(cwd, '.scriptdrift');
      await mkdir(join(storage, 'baselines'), { recursive: true });
      await writeFile(join(storage, '.gitignore'), STORAGE_GITIGNORE, 'utf8');

      // Make sure .env files are not committed by accident.
      const rootIgnore = join(cwd, '.gitignore');
      const existing = (await pathExists(rootIgnore)) ? await readFile(rootIgnore, 'utf8') : '';
      if (!/^\.env$/m.test(existing)) {
        await writeFile(rootIgnore, `${existing}${existing && !existing.endsWith('\n') ? '\n' : ''}# ScriptDrift: never commit secrets\n.env\n`, 'utf8');
      }

      if (g.json) {
        printJson({ config: configPath, storage });
        return;
      }
      print(color.green(`Created ${configPath}`));
      print(color.green(`Created ${storage}/ (reports, cache and state are git-ignored)`));
      print();
      print('Next steps:');
      print(`  1. Edit ${color.bold('scriptdrift.yml')} and list the sites and pages to monitor.`);
      print(`  2. Run ${color.bold('npx scriptdrift scan')} to see which scripts your pages load.`);
      print(`  3. Review the results and run ${color.bold('npx scriptdrift baseline')} to approve them.`);
    });
}
