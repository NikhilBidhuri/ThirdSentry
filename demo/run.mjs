#!/usr/bin/env node
// `npm run demo`: watch ThirdSentry catch a Magecart-style attack on a local shop.
//
//   1. start the "Acme Outfitters" demo shop (fake .test hosts on 127.0.0.1)
//   2. scan it and approve the clean state as the baseline
//   3. compromise the shop (skimmer in a vendor script, lookalike-domain loader,
//      exfiltration beacon, tampered payment form, CSP removed)
//   4. scan again and write JSON + HTML reports
//
// Options:
//   --open         open the HTML report in your browser when done
//   --keep-server  keep the shop running afterwards so you can run CLI commands yourself
//   --quiet        only print the step banners and the final summary
//   --port <n>     serve the shop on this port (default: a free port)
//
// Everything runs locally. Nothing is sent anywhere.

import { spawn, spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';
import { createDemoServer, demoConfig } from './site/server.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const WORK = join(ROOT, 'demo', '.work');
const BIN = join(ROOT, 'dist', 'cli', 'bin.js');
const argv = process.argv.slice(2);
const args = new Set(argv);
const portArg = argv.indexOf('--port');
const listenPort = portArg >= 0 ? Number(argv[portArg + 1]) : 0;
const quiet = args.has('--quiet');

const tty = process.stdout.isTTY && !process.env.NO_COLOR;
const c = (code) => (s) => (tty ? `\u001b[${code}m${s}\u001b[0m` : s);
const bold = c('1');
const cyan = c('36');
const red = c('1;31');
const gray = c('90');
const green = c('32');

function banner(step, text) {
  process.stdout.write(`\n${cyan('━━━')} ${bold(`${step}`)} ${text} ${cyan('━'.repeat(Math.max(3, 60 - text.length)))}\n\n`);
}

/** Run the built CLI against the demo config; resolves to the exit code. */
function thirdsentry(...cliArgs) {
  const config = join(WORK, 'thirdsentry.yml');
  if (!quiet) process.stdout.write(gray(`$ thirdsentry ${cliArgs.join(' ')}\n`));
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [BIN, '--config', config, ...cliArgs], { stdio: ['ignore', quiet ? 'ignore' : 'inherit', 'pipe'] });
    // Structured logs go to stderr as JSON lines; show only errors (level >= 50) and anything that is not a log line.
    let buf = '';
    child.stderr.on('data', (d) => {
      buf += d;
      let i;
      while ((i = buf.indexOf('\n')) >= 0) {
        const line = buf.slice(0, i);
        buf = buf.slice(i + 1);
        let level = 100;
        try {
          level = JSON.parse(line).level ?? 100;
        } catch {
          // not a log line
        }
        if (level >= 50) process.stderr.write(`${line}\n`);
      }
    });
    child.on('error', reject);
    child.on('exit', (code) => resolve(code ?? 1));
  });
}

function openInBrowser(file) {
  const cmd = process.platform === 'win32' ? 'cmd' : process.platform === 'darwin' ? 'open' : 'xdg-open';
  const cmdArgs = process.platform === 'win32' ? ['/c', 'start', '""', file] : [file];
  spawn(cmd, cmdArgs, { stdio: 'ignore', detached: true }).unref();
}

async function main() {
  if (!existsSync(BIN)) {
    process.stdout.write(gray('dist/ not found, building ThirdSentry first (npm run build)...\n'));
    const build = spawnSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['run', 'build'], { cwd: ROOT, stdio: 'inherit', shell: process.platform === 'win32' });
    if (build.status !== 0) throw new Error('build failed');
  }

  const shop = createDemoServer();
  const port = await shop.start(listenPort);
  await rm(WORK, { recursive: true, force: true });
  await mkdir(WORK, { recursive: true });
  await writeFile(
    join(WORK, 'thirdsentry.yml'),
    `# Generated by demo/run.mjs for the local demo shop on port ${port}.\n${stringify(demoConfig(port))}`,
  );

  try {
    process.stdout.write(`${bold('ThirdSentry demo')}: the Acme Outfitters shop is running on 127.0.0.1:${port}\n`);
    process.stdout.write(gray(`config: ${relative(process.cwd(), join(WORK, 'thirdsentry.yml'))}\n`));

    banner('1/4', 'Scan the clean shop');
    await thirdsentry('scan', '--allow-missing-baseline', '--fail-on', 'none', '--format', 'json');

    banner('2/4', 'Approve what we saw as the baseline');
    const approved = await thirdsentry('baseline', '--yes', '--reason', 'demo: reviewed the clean shop');
    if (approved !== 0) throw new Error('baseline failed');

    banner('3/4', 'Attacker compromises the shop');
    shop.setState('compromised');
    for (const line of [
      'pay.js from the payment vendor now carries a card skimmer',
      'a "jquery" loader from the lookalike domain cdn-assets-cloud.test runs obfuscated eval',
      'card data is beaconed to collect.exfil.test',
      'the checkout form posts to the attacker and asks for a card PIN',
      'the checkout page no longer sends Content-Security-Policy or X-Frame-Options',
    ]) {
      process.stdout.write(`  ${red('✗')} ${line}\n`);
    }

    banner('4/4', 'Scan again');
    const reportDir = join(WORK, 'report');
    const code = await thirdsentry('scan', '--fail-on', 'high', '--format', 'json,html', '--output', reportDir);

    const html = join(reportDir, 'report.html');
    process.stdout.write(`\n${code === 1 ? red('scan exited 1: high/critical findings, a CI job would fail here') : `scan exited ${code}`}\n`);
    process.stdout.write(`${green('HTML report:')} ${html}\n`);
    if (args.has('--open')) openInBrowser(html);

    if (args.has('--keep-server')) {
      process.stdout.write(
        `\nThe shop keeps running. Try:\n` +
          `  node dist/cli/bin.js --config ${relative(process.cwd(), join(WORK, 'thirdsentry.yml'))} diff\n` +
          `  curl http://127.0.0.1:${port}/__state/clean      # undo the attack\n` +
          `Press Ctrl+C to stop.\n`,
      );
      await new Promise((resolve) => process.once('SIGINT', resolve));
    }
    return code === 1 ? 0 : 1; // the demo "succeeds" when the attack is caught
  } finally {
    await shop.stop();
  }
}

main().then(
  (code) => process.exit(code),
  (err) => {
    process.stderr.write(`demo failed: ${err instanceof Error ? err.message : String(err)}\n`);
    process.exit(1);
  },
);
